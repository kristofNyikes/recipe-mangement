import { randomUUID } from "node:crypto";
import { mkdir, unlink, writeFile } from "node:fs/promises";
import { NextRequest, NextResponse } from "next/server";
import { revalidatePath } from "next/cache";

import prisma from "@/prisma/client";
import {
  detectRecipeImageType,
  getRecipeImagePath,
  isRecipeImageFilename,
  MAX_RECIPE_IMAGE_SIZE,
  RECIPE_IMAGE_DIR,
} from "@/app/lib/recipeImages";

interface Params {
  params: Promise<{ slug: string }>;
}

export const runtime = "nodejs";

export async function POST(request: NextRequest, { params }: Params) {
  let savedPath: string | undefined;
  let databaseUpdated = false;

  try {
    const { slug } = await params;

    const recipe = await prisma.recipe.findUnique({
      where: { slug },
      select: { slug: true, imagePath: true },
    });

    if (!recipe) {
      return NextResponse.json({ error: "Recipe not found" }, { status: 404 });
    }

    const formData = await request.formData();
    const file = formData.get("image");

    if (!(file instanceof File) || file.size === 0) {
      return NextResponse.json(
        { error: "Please upload an image using the 'image' field" },
        { status: 400 },
      );
    }

    if (file.size > MAX_RECIPE_IMAGE_SIZE) {
      return NextResponse.json(
        { error: "Image must be 5 MB or smaller" },
        { status: 413 },
      );
    }

    const buffer = Buffer.from(await file.arrayBuffer());
    const imageType = detectRecipeImageType(buffer);

    if (!imageType || file.type !== imageType.mimeType) {
      return NextResponse.json(
        { error: "Only valid JPEG, PNG, and WebP images are supported" },
        { status: 400 },
      );
    }

    const filename = `${randomUUID()}.${imageType.extension}`;
    savedPath = getRecipeImagePath(filename);

    await mkdir(RECIPE_IMAGE_DIR, { recursive: true });
    await writeFile(savedPath, buffer, { flag: "wx" });

    const updatedRecipe = await prisma.recipe.update({
      where: { slug },
      data: { imagePath: filename },
      select: { slug: true, imagePath: true },
    });

    databaseUpdated = true;

    // Remove the previous image after the database update succeeds.
    if (
      recipe.imagePath &&
      isRecipeImageFilename(recipe.imagePath) &&
      recipe.imagePath !== filename
    ) {
      try {
        await unlink(getRecipeImagePath(recipe.imagePath));
      } catch (error) {
        console.error("Could not remove previous recipe image:", error);
      }
    }

    revalidatePath("/main");

    return NextResponse.json(
      {
        data: {
          ...updatedRecipe,
          imageUrl: `/api/v1/recipe/image/${filename}`,
        },
      },
      { status: 200 },
    );
  } catch (error) {
    // Avoid leaving the newly uploaded file behind if saving to the DB fails.
    if (savedPath && !databaseUpdated) {
      await unlink(savedPath).catch(() => {});
    }

    console.error("Failed to upload recipe image:", error);

    return NextResponse.json(
      { error: "Failed to upload recipe image" },
      { status: 500 },
    );
  }
}

export async function DELETE(_request: NextRequest, { params }: Params) {
  try {
    const { slug } = await params;

    const recipe = await prisma.recipe.findUnique({
      where: { slug },
      select: { slug: true, imagePath: true },
    });

    if (!recipe) {
      return NextResponse.json({ error: "Recipe not found" }, { status: 404 });
    }

    if (!recipe.imagePath) {
      return NextResponse.json(
        { error: "Recipe has no image to delete" },
        { status: 404 },
      );
    }

    // Only delete filenames generated by our upload endpoint.
    if (!isRecipeImageFilename(recipe.imagePath)) {
      console.error("Invalid recipe image filename:", recipe.imagePath);

      return NextResponse.json(
        { error: "Stored recipe image path is invalid" },
        { status: 500 },
      );
    }

    // Clear the database reference first.
    await prisma.recipe.update({
      where: { slug },
      data: { imagePath: null },
    });

    // Remove the file. A missing file is already effectively deleted.
    try {
      await unlink(getRecipeImagePath(recipe.imagePath));
    } catch (error) {
      if (
        !(error instanceof Error && "code" in error && error.code === "ENOENT")
      ) {
        // The database reference is already cleared, so report the cleanup
        // failure rather than pretending everything succeeded.
        console.error("Could not remove recipe image file:", error);

        revalidatePath("/main");

        return NextResponse.json(
          { error: "Image reference removed, but file cleanup failed" },
          { status: 500 },
        );
      }
    }

    revalidatePath("/main");

    return NextResponse.json({
      data: {
        slug: recipe.slug,
        imagePath: null,
      },
    });
  } catch (error) {
    console.error("Failed to delete recipe image:", error);

    return NextResponse.json(
      { error: "Failed to delete recipe image" },
      { status: 500 },
    );
  }
}
